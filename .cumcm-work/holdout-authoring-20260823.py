def main() -> int:
    output_root = ROOT / "holdout-candidates-20260823-frozen"
    for key, variants in REWRITES.items():
        scene, stem = key.split("/", 1)
        source = ROOT / scene / "holdout" / "sources" / f"{stem}.tex"
        source_text = source.read_text(encoding="utf-8-sig")
        output = output_root / scene
        output.mkdir(parents=True, exist_ok=True)
        candidates = []
        for index, variant in enumerate(variants, start=1):
            if variant == source_text:
                raise ValueError(f"candidate equals source: {key} t{index}")
            target = output / f"{stem}-t{index}.tex"
            target.write_text(variant, encoding="utf-8")
            candidates.append(variant)
        if len(set(candidates)) != 3:
            raise ValueError(f"duplicate variants: {key}")
    print(f"HOLDOUT CANDIDATES READY root={output_root}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
