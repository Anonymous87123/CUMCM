def normalized_lines(text: str) -> list[str]:
    return text.replace("\r\n", "\n").replace("\r", "\n").splitlines(keepends=True)


def digest_span(text: str, start_line: int, end_line: int) -> str:
    lines = normalized_lines(text)
    raw = "".join(lines[start_line - 1 : end_line]).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def groups(indices: list[int]) -> list[tuple[int, int]]:
    if not indices:
        return []
    out: list[tuple[int, int]] = []
    start = previous = indices[0]
    for value in indices[1:]:
        if value != previous + 1:
            out.append((start, previous))
            start = value
        previous = value
    out.append((start, previous))
    return out


def protected_tokens(text: str) -> list[str]:
    return re.findall(r"\[\[PROTECTED:[^\]]+\]\]", text)


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def write_json(path: Path, payload: dict) -> None:
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def author_rewrite(unit_id: str, changes: list[tuple[str, str]]) -> None:
    chunk = load_json(CHUNKS / f"{unit_id}.json")
    bundle_path = REWRITES / f"{unit_id}.json"
    bundle = load_json(bundle_path)
    before = chunk["masked_text"]
    after = before
    for old, new in changes:
        count = after.count(old)
        if count != 1:
            raise RuntimeError(f"{unit_id}: replacement match count {count}: {old[:48]!r}")
        after = after.replace(old, new, 1)

    if protected_tokens(before) != protected_tokens(after):
        raise RuntimeError(f"{unit_id}: protected placeholder drift")
    before_lines = normalized_lines(before)
    after_lines = normalized_lines(after)
    if len(before_lines) != len(after_lines):
        raise RuntimeError(f"{unit_id}: physical line count changed")
    changed = [i for i, pair in enumerate(zip(before_lines, after_lines), start=1) if pair[0] != pair[1]]
    if not changed:
        raise RuntimeError(f"{unit_id}: no actual change")

    spans = []
    operations = []
    for index, (start, end) in enumerate(groups(changed), start=1):
        span_id = f"S{index}"
        op_id = f"O{index}"
        spans.append(
            {
                "id": span_id,
                "start_line": start,
                "end_line": end,
                "sha256": digest_span(before, start, end),
            }
        )
        operations.append(
            {
                "id": op_id,
                "kind": "REWRITE_STYLE_SHELL",
                "source_span_ids": [span_id],
                "target_signals": ["STYLE-MODELING-NATURAL-RHYTHM"],
                "summary": SUMMARIES[unit_id],
            }
        )

    bundle["decision"] = "REWRITE"
    bundle["masked_text"] = after
    bundle["rewrite_intent"] = {
        "summary": SUMMARIES[unit_id],
        "operations": operations,
        "source_spans": spans,
        "target_signals": ["STYLE-MODELING-NATURAL-RHYTHM"],
    }
    bundle["keep_reasons"] = KEEP_REASONS.get(unit_id, {})
    bundle["template_field_edit_scope"] = None
    bundle.pop("reason", None)
    bundle.pop("evidence_spans", None)
    write_json(bundle_path, bundle)


def author_no_change(unit_id: str, reason: str) -> None:
    chunk = load_json(CHUNKS / f"{unit_id}.json")
