    templates = {
        path.stem
        for path in REWRITES.glob("U-*.json")
        if path.name != "scaffold_metadata.json"
    }
    if expected != templates:
        raise RuntimeError(
            f"decision coverage mismatch missing={sorted(templates - expected)} extra={sorted(expected - templates)}"
        )
