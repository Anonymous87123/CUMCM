foreach ($unitId in $expectedUnits) {
    if (-not $edits.ContainsKey($unitId)) { $missing += "Missing edits for $unitId"; continue }
    $bundlePath = Join-Path $rewriteDir "$unitId.json"
    $candidate = [string]((Get-Content $bundlePath -Raw -Encoding UTF8 | ConvertFrom-Json).masked_text)
    foreach ($pair in $edits[$unitId]) {
        $old = [string]$pair[0]
        $new = [string]$pair[1]
        if ($candidate.Contains($old)) {
            $candidate = $candidate.Replace($old, $new)
        } elseif (-not $candidate.Contains($new)) {
            $missing += "${unitId}: $old"
        }
    }
