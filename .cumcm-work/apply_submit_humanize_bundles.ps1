foreach ($unitId in $expectedUnits) {
    if (-not $edits.ContainsKey($unitId)) { throw "Missing edits for $unitId" }
    $bundlePath = Join-Path $rewriteDir "$unitId.json"
    $bundle = Get-Content $bundlePath -Raw -Encoding UTF8 | ConvertFrom-Json
    $before = [string]$bundle.masked_text
    $after = $before
    $applied = 0
    foreach ($pair in $edits[$unitId]) {
        $old = [string]$pair[0]
        $new = [string]$pair[1]
        if ($after.Contains($old)) {
            $after = $after.Replace($old, $new)
            $applied++
        } elseif (-not $after.Contains($new)) {
            throw "Neither old nor rewritten text found in ${unitId}: $old"
        }
    }
    if ($applied -eq 0) {
        Write-Output "ALREADY_UPDATED $unitId"
        continue
    }

    $summary = '调整目录式、均匀并列式表达，保留具体判断、程序动作与使用边界'
    $probeRaw = & python $intentBuilder --run-dir $runDir --unit-id $unitId `
        --start-line 1 --end-line 1 `
        --operation-kind REWRITE_STYLE_SHELL `
        --target-signal HUM-JUDGMENT-TRACE `
        --target-signal RHYTHM-UNIFORM-SEQUENCE `
        --summary $summary --format json
    if ($LASTEXITCODE -ne 0) { throw "Intent line-count probe failed for $unitId" }
    $probe = ($probeRaw -join "`n") | ConvertFrom-Json
    $intentRaw = & python $intentBuilder --run-dir $runDir --unit-id $unitId `
        --start-line 1 --end-line ([int]$probe.source_line_count) `
        --operation-kind REWRITE_STYLE_SHELL `
        --target-signal HUM-JUDGMENT-TRACE `
        --target-signal RHYTHM-UNIFORM-SEQUENCE `
        --summary $summary --format json
    if ($LASTEXITCODE -ne 0) { throw "Intent builder failed for $unitId" }
    $intentPayload = ($intentRaw -join "`n") | ConvertFrom-Json

    $bundle.masked_text = $after
    $bundle.rewrite_intent = $intentPayload.rewrite_intent
    $json = $bundle | ConvertTo-Json -Depth 30
    [System.IO.File]::WriteAllText($bundlePath, $json + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Output "UPDATED $unitId replacements=$($edits[$unitId].Count)"
